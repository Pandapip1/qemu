#!/usr/bin/env python3
"""Generate resets.py (register offsets, names, reset values and IRQ numbers) from the
Silicon Labs EFR32BG22 device headers.
Usage: gen_resets.py <path to .../Device/SiliconLabs/EFR32BG22/Include>
Nested register groups (e.g. GPIO P[n], TIMER CC[n]) are flattened as 'P[1].DOUT'."""
import glob, os, re, sys

inc = sys.argv[1]
out = {}


def parse_structs(text):
    """name -> list of (member_name, type, count) in declaration order"""
    structs = {}
    for body, name in re.findall(r"typedef struct \{(.*?)\}\s*(\w+)_TypeDef;", text, re.S):
        mem = []
        for line in body.split("\n"):
            mm = re.match(r"\s*(?:__IM|__IOM|__OM)?\s*(\w+)\s+(\w+)(?:\[(\d+)U?\])?;", line)
            if mm:
                mem.append((mm.group(2), mm.group(1), int(mm.group(3) or 1)))
        structs[name] = mem
    return structs


def size_of(structs, name):
    return sum((4 if t == "uint32_t" else size_of(structs, t[:-len("_TypeDef")])) * c
               for _, t, c in structs[name])


def flatten(structs, name, base, prefix, regs, limit=0x1000):
    off = base
    for mname, mtype, cnt in structs[name]:
        if mtype == "uint32_t":
            for i in range(cnt):
                if not mname.startswith("RESERVED") and off - base < limit:
                    regs[off] = prefix + mname + (f"[{i}]" if cnt > 1 else "")
                off += 4
        else:
            sub = mtype[:-len("_TypeDef")]
            for i in range(cnt):
                flatten(structs, sub, off, prefix + mname + (f"[{i}]" if cnt > 1 else "") + ".", regs, 0x10000)
                off += size_of(structs, sub)


ALL = {}
for path in sorted(glob.glob(os.path.join(inc, "efr32bg22_*.h"))):
    ALL.update(parse_structs(open(path).read()))

for path in sorted(glob.glob(os.path.join(inc, "efr32bg22_*.h"))):
    t = open(path).read()
    stem = os.path.basename(path)[len("efr32bg22_"):-2].upper()
    structs = ALL
    if stem not in structs:
        continue
    regs = {}
    flatten(structs, stem, 0, "", regs)
    # drop the SET/CLR/TGL alias copies (they live at +0x1000/+0x2000/+0x3000)
    regs = {o: n for o, n in regs.items() if o < 0x1000}
    res = {}
    for o, n in regs.items():
        base = n.split(".")[-1].split("[")[0]
        rv = re.search(r"#define _%s_%s_RESETVALUE\s+(0x[0-9A-Fa-f]+)" % (stem, base), t) \
            or re.search(r"#define _%s_%s_RESETVALUE\s+(0x[0-9A-Fa-f]+)" % (stem, n.replace(".", "_").replace("[", "").replace("]", "")), t)
        res[o] = (n, int(rv.group(1), 16) if rv else 0)
    out[stem] = res

dev = open(os.path.join(inc, "efr32bg22c224f512im40.h")).read()
irqs = {n: int(v) for n, v in re.findall(r"^\s*(\w+)_IRQn\s*=\s*(\d+),", dev, re.M)}
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "resets.py"), "w") as f:
    f.write("# Generated by gen_resets.py from the EFR32BG22 device headers (Zlib licensed SDK).\n")
    f.write("REGS = {\n")
    for p, regs in out.items():
        f.write("    %r: {\n" % p)
        for o, (n, v) in sorted(regs.items()):
            f.write("        0x%03x: (%r, 0x%08x),\n" % (o, n, v))
        f.write("    },\n")
    f.write("}\nIRQS = %r\n" % irqs)
print("wrote", len(out), "peripherals")
